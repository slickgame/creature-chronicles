import test from 'node:test';
import assert from 'node:assert/strict';
import { createNewGameSave } from './helpers/establishedSave.ts';
import { getVariantDefinition } from '@/data/creatures';
import { getChoreSkillXpToNext, normalizeCreatureChoreSkills } from '@/data/choreSkills';
import { getWorkSkillLedger } from '@/data/workSkillLedger';
import { workPreview, workResourceSite } from '@/data/farmResources';
test('legacy shared Production migrates once; Hunting and Husbandry train independently', () => {
  const save = createNewGameSave('Independent work skills', 0);
  const creature = save.creatures!.find(c => getVariantDefinition(c.variantId).family === 'bovine')!;
  creature.sex = 'female'; creature.energy = 100; creature.abilities = [];
  const skills = normalizeCreatureChoreSkills(creature);
  skills.production = { level: 8, xp: 15, xpToNext: getChoreSkillXpToNext(8), lifetimeXp: 850 };
  const { hunting: _hunting, ...legacy } = skills;
  creature.choreSkills = legacy as typeof creature.choreSkills;
  const before = structuredClone(save), migrated = normalizeCreatureChoreSkills(creature);
  assert.deepEqual(migrated.hunting, migrated.production);
  assert.deepEqual(normalizeCreatureChoreSkills({ ...creature, choreSkills: migrated }), migrated);
  const preview = workPreview(save, 'hunting', creature);
  assert.equal(preview.details.skillLabel, 'Hunting');
  const hunt = workResourceSite(save, 'hunting', creature.creatureId);assert.ok(hunt.ok, hunt.message);assert.deepEqual(save, before);
  const hunted = hunt.save.creatures!.find(c => c.creatureId === creature.creatureId)!;
  assert.equal(hunted.choreSkills!.hunting.xp, 15 + preview.xp);
  assert.deepEqual(hunted.choreSkills!.production, migrated.production);
  const huntingAfter = structuredClone(hunted.choreSkills!.hunting), dairyPreview = workPreview(hunt.save, 'dairy', hunted);
  assert.equal(dairyPreview.details.skillLabel, 'Husbandry');
  const dairy = workResourceSite(hunt.save, 'dairy', hunted.creatureId);assert.ok(dairy.ok, dairy.message);
  const milked = dairy.save.creatures!.find(c => c.creatureId === creature.creatureId)!;
  assert.deepEqual(milked.choreSkills!.hunting, huntingAfter);
  assert.equal(milked.choreSkills!.production.xp, 15 + dairyPreview.xp);
});
test('ledger retains saved XP and labels unfinished features without changing records', () => {
  const creature = createNewGameSave('Work ledger', 0).creatures![0];creature.choreSkills = normalizeCreatureChoreSkills(creature);
  creature.choreSkills.hauling = { level: 7, xp: 29, xpToNext: 125, lifetimeXp: 601 };
  const before = structuredClone(creature), entries = getWorkSkillLedger(creature);
  assert.deepEqual(entries.map(e => e.title), ['Harvesting', 'Material Gathering', 'Husbandry', 'Hunting', 'Crafting', 'Cooking', 'Breeding', 'Cleaning']);
  assert.deepEqual(entries.find(e => e.id === 'materials')!.progress, creature.choreSkills.hauling);
  assert.equal(entries.find(e => e.id === 'breeding')!.progress, null);
  assert.ok(entries.find(e => e.id === 'cleaning')!.planned);
  for (const id of ['crafting', 'cooking']) assert.equal(entries.find(e => e.id === id)!.planned, undefined);
  assert.deepEqual(creature, before);
});
